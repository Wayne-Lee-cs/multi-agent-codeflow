_FAKE_CLAUDE_SCRIPT = textwrap.dedent('''\
    """Fake claude -p that reads stdin prompt and writes a file in CWD."""
    import json, os, sys

    prompt = sys.stdin.read()
    # Emit stream-json init
    print(json.dumps({"type": "system", "subtype": "init", "model": "fake-model"}))
    sys.stdout.flush()

    # Write a file based on the task — the file name is derived from the prompt
    # Convention: prompt contains "FILE:<name>" to tell us what to create
    import re
    m = re.search(r"FILE:(\\S+)", prompt)
    if m:
        filepath = m.group(1)
        os.makedirs(os.path.dirname(filepath), exist_ok=True) if os.path.dirname(filepath) else None
        with open(filepath, "w") as f:
            f.write(f"# generated by task\\n# prompt: {prompt[:50]}\\n")

    # Emit result
    print(json.dumps({
        "type": "result",
        "subtype": "success",
        "usage": {"input_tokens": 100, "output_tokens": 50}
    }))
    sys.stdout.flush()
''')

