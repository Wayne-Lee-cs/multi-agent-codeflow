@pytest.mark.asyncio
async def test_e2e_token_budget(e2e_repo: Path, fake_claude: Path) -> None:
    """Token budget enforcement stops dispatching new tasks."""
    from cagent.dispatcher import run as dispatch_run
    from cagent.memory import RunMemory
    from cagent.progress import Dashboard
    from cagent.worktree import current_head

    run_dir = e2e_repo / ".cagent" / "runs" / "e2e-budget"
    run_dir.mkdir(parents=True)

    base_sha = current_head(e2e_repo)

    tasks = [
        Task(id="001", prompt="Task A FILE:a.py", branch="cagent/e2e-budget/task-001"),
        Task(id="002", prompt="Task B FILE:b.py", branch="cagent/e2e-budget/task-002"),
        Task(id="003", prompt="Task C FILE:c.py", branch="cagent/e2e-budget/task-003"),
    ]
    dump_state(run_dir, tasks)

    dashboard = Dashboard(run_dir)
    memory = RunMemory(run_dir)

    orig_exec = asyncio.create_subprocess_exec

    async def patched_exec(*args, **kwargs):
        args_list = list(args)
        if args_list and args_list[0] == "claude":
            args_list = [sys.executable, str(fake_claude)]
        return await orig_exec(*args_list, **kwargs)

    with patch("cagent.agent._resolve_claude", return_value="claude"), \
         patch("cagent.agent.prepare_sandbox"), \
         patch("cagent.agent.asyncio.create_subprocess_exec", side_effect=patched_exec):
        results = await dispatch_run(
            tasks=tasks,
            concurrency=1,  # sequential so budget check works between tasks
            run_dir=run_dir,
            base_sha=base_sha,
            repo_root=e2e_repo,
            timeout=30,
            dashboard=dashboard,
            memory=memory,
            max_tokens=200,  # very low budget — first task uses 150 tokens
        )

    # At least one task should have been budget-stopped
    budget_failed = [r for r in results if r.fail_reason and "budget" in r.fail_reason]
    done = [r for r in results if r.status == "done"]
    assert len(done) >= 1
    assert len(budget_failed) >= 1
