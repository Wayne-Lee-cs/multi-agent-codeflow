@pytest.mark.asyncio
async def test_e2e_two_tasks_no_deps(e2e_repo: Path, fake_claude: Path) -> None:
    """Two independent tasks → both commit → integration branch."""
    from cagent.dispatcher import run as dispatch_run
    from cagent.integrator import integrate
    from cagent.memory import RunMemory
    from cagent.progress import Dashboard
    from cagent.worktree import current_head

    run_dir = e2e_repo / ".cagent" / "runs" / "e2e-test-1"
    run_dir.mkdir(parents=True)

    base_sha = current_head(e2e_repo)

    tasks = [
        Task(id="001", prompt="Create module A FILE:module_a.py", branch="cagent/e2e-test-1/task-001"),
        Task(id="002", prompt="Create module B FILE:module_b.py", branch="cagent/e2e-test-1/task-002"),
    ]
    dump_state(run_dir, tasks)

    dashboard = Dashboard(run_dir)
    memory = RunMemory(run_dir)

    orig_exec = asyncio.create_subprocess_exec

    async def patched_exec(*args, **kwargs):
        args_list = list(args)
        if args_list and args_list[0] == "claude":
            args_list = [sys.executable, str(fake_claude)]
        return await orig_exec(*args_list, **kwargs)

    with patch("cagent.agent._resolve_claude", return_value="claude"), \
         patch("cagent.agent.prepare_sandbox"), \
         patch("cagent.agent.asyncio.create_subprocess_exec", side_effect=patched_exec):
        results = await dispatch_run(
            tasks=tasks,
            concurrency=2,
            run_dir=run_dir,
            base_sha=base_sha,
            repo_root=e2e_repo,
            timeout=30,
            dashboard=dashboard,
            memory=memory,
        )

    done_count = sum(1 for r in results if r.status == "done")
    assert done_count == 2, f"Expected 2 done, got: {[(r.task_id, r.status, r.fail_reason) for r in results]}"

    # Both tasks should have commit SHAs
    for r in results:
        assert r.commit_sha is not None

    # Integration
    integration_sha = await integrate(
        tasks=tasks,
        run_dir=run_dir,
        base_sha=base_sha,
        repo_root=e2e_repo,
        dashboard=dashboard,
    )

    assert integration_sha != base_sha


